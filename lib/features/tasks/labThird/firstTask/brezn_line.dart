import 'dart:math' show Point;

/// Возвращает список точек [Point<int>], аппроксимирующих отрезок от (x0, y0) до (x1, y1).
/// Алгоритм Брезенхема, целочисленная версия.
List<Point<int>> bresenham(int x0, int y0, int x1, int y1) {
  final points = <Point<int>>[];

  // Абсолютные расстояния
  int dx = (x1 - x0).abs();
  int dy = (y1 - y0).abs();

  // Направления приращений
  int stepX = x0 < x1 ? 1 : -1;
  int stepY = y0 < y1 ? 1 : -1;

  // Текущие координаты
  int x = x0;
  int y = y0;

  // Если отрезок горизонтальный или вертикальный – можно сразу сгенерировать,
  // но общий алгоритм тоже справится. Оставим как есть.

  if (dx > dy) {
    // Наклон менее 45°: основной шаг по X
    int d = 2 * dy - dx;         // начальное значение ошибки
    int inc1 = 2 * dy;           // приращение для горизонтального шага
    int inc2 = 2 * (dy - dx);    // приращение для диагонального шага

    for (int i = 0; i <= dx; i++) {
      points.add(Point(x, y));
      if (d < 0) {
        // горизонтальный шаг
        d += inc1;
      } else {
        // диагональный шаг (меняем y)
        y += stepY;
        d += inc2;
      }
      x += stepX;
    }
  } else {
    // Наклон более 45° (или равен 45°): основной шаг по Y
    int d = 2 * dx - dy;         // начальное значение ошибки
    int inc1 = 2 * dx;           // приращение для вертикального шага
    int inc2 = 2 * (dx - dy);    // приращение для диагонального шага

    for (int i = 0; i <= dy; i++) {
      points.add(Point(x, y));
      if (d < 0) {
        // вертикальный шаг
        d += inc1;
      } else {
        // диагональный шаг (меняем x)
        x += stepX;
        d += inc2;
      }
      y += stepY;
    }
  }

  return points;
}